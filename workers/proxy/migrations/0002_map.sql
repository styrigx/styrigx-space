-- 代理订阅 v1.13：机场源节点处理（sub map / sub fp）。
-- 丢弃词表、映射词表（源词 → ISO 两位码）、ISO 3166-1 国家码对照表（固定数据，没有命令能改）。
-- 源词两张表合起来唯一（接口校验）；初始词原样取自 Gray 现用手机配置。

ALTER TABLE sources ADD COLUMN unmatched INTEGER NOT NULL DEFAULT 0; -- 上次处理后没加上国旗的节点数（只机场源）

CREATE TABLE iso_country (
  a2   TEXT PRIMARY KEY,      -- ISO 3166-1 alpha-2
  a3   TEXT NOT NULL UNIQUE,  -- ISO 3166-1 alpha-3
  flag TEXT NOT NULL
);

CREATE TABLE map_drop (
  word TEXT PRIMARY KEY,      -- 源词（小写）：节点名含它 → 整条丢掉
  pos  INTEGER NOT NULL
);

CREATE TABLE map_flag (
  word TEXT PRIMARY KEY,      -- 源词（小写）：节点名含它 → 加目标国旗
  code TEXT NOT NULL REFERENCES iso_country(a2),
  pos  INTEGER NOT NULL       -- 匹配顺序，先命中先用
);

